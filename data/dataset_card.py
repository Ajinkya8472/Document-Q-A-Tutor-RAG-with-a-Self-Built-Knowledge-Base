"""Writes DATASET_CARD.md (numbers for your slides).   python dataset_card.py corpus qa_dataset_reviewed.json"""
import sys, os, json, collections
from rag_tutor import load_corpus
chunks = load_corpus(sys.argv[1]); qa = json.load(open(sys.argv[2], encoding="utf-8"))
docs = collections.Counter(c["doc"] for c in chunks)
words = sum(len(c["text"].split()) for c in chunks)
wiki = sum(1 for d in docs if d.startswith("wiki_")); own = len(docs) - wiki
A = [x for x in qa if x["answerable"]]; U = [x for x in qa if not x["answerable"]]
L = [
 "# Dataset card", "", "## Corpus",
 f"- Documents: {len(docs)} ({own} own documents, {wiki} Wikipedia articles, CC BY-SA)",
 f"- Words: {words:,}   Chunks: {len(chunks):,} (~110 words, sentence-aware)",
 f"- Largest documents: " + ", ".join(f"{d} ({n})" for d, n in docs.most_common(3)), "",
 "## Q&A set",
 f"- Answerable questions: {len(A)} (generated by Qwen2.5-1.5B from corpus chunks, filtered for grounding)",
 f"- Hand-verified: {sum(1 for x in A if x.get('verified'))}",
 f"- Unanswerable questions: {len(U)} ({sum(1 for x in U if x.get('kind','').startswith('near'))} near-topic fictional, {sum(1 for x in U if x.get('kind')=='off-topic')} off-topic)",
 f"- Documents covered by answerable questions: {len(set(x['gold_doc'] for x in A))}",
 f"- Mean question length: {sum(len(x['q'].split()) for x in A)/max(len(A),1):.1f} words", "",
 "## Licence / provenance",
 "- Wikipedia text: CC BY-SA 4.0 (attribution: Wikipedia contributors). Own documents: team papers.",
 "- Q&A pairs: machine-generated, filtered by rules, partly human-verified."]
open("DATASET_CARD.md", "w", encoding="utf-8").write("\n".join(L)); print("\n".join(L))